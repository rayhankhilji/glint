#!/usr/bin/env python3
"""Compiles Design/tokens.json into SaccadeUI/DesignSystem/SaccadeColorTokens.swift (generated; never edit by hand).

Chrome tokens become appearance-aware colors (NSColor dynamic provider), so the Swift package needs no asset
catalog. Usage: python3 scripts/design/build_tokens.py [--check]
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "Design/tokens.json"
OUTPUT = ROOT / "Packages/SaccadeKit/Sources/SaccadeUI/DesignSystem/SaccadeColorTokens.swift"


def rgba(hex_value):
    h = hex_value.lstrip("#")
    if len(h) not in (6, 8):
        raise ValueError(f"bad color {hex_value}")
    r, g, b = (int(h[i : i + 2], 16) for i in (0, 2, 4))
    a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
    return r, g, b, a


def swift_color(hex_value):
    r, g, b, a = rgba(hex_value)
    return f"rgba(0x{r:02X}, 0x{g:02X}, 0x{b:02X}, {a:.3f})"


def generate():
    tokens = json.loads(SOURCE.read_text())
    out = [
        "// Generated by scripts/design/build_tokens.py from Design/tokens.json. Do not edit by hand.",
        "// swiftlint:disable file_length — generated token table", "",
        "import AppKit", "import SwiftUI", "",
        "/// Color tokens (DESIGN_SYSTEM §2). Chrome tokens adapt to light/dark; overlay tokens are fixed because the",
        "/// overlay sits on arbitrary content.",
        "public enum SaccadeColor {",
    ]
    for name, t in tokens["chrome"].items():
        out.append(f"    /// {t['use']}")
        out.append(f"    public static var {name}: Color {{ dynamic(light: {swift_color(t['light'])}, dark: {swift_color(t['dark'])}) }}")
    out.append("")
    for name, t in tokens["overlay"].items():
        swift_name = "overlay" + name[0].upper() + name[1:]
        out.append(f"    /// {t['use']}")
        out.append(f"    public static var {swift_name}: Color {{ Color(nsColor: {swift_color(t['value'])}) }}")
    out += ["", "    /// Every chrome token by name, for swatch snapshots and tests.",
            "    public static let chromeTokenNames = [" + ", ".join(f'"{n}"' for n in tokens["chrome"]) + "]", "",
            "    /// A chrome token by name.", "    public static func chrome(_ name: String) -> Color {", "        switch name {"]
    out += [f'        case "{n}": {n}' for n in tokens["chrome"]]
    out += ["        default: text", "        }", "    }", "}", ""]
    return "\n".join(out)


def main(argv):
    swift = generate()
    if "--check" in argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != swift:
            print("SaccadeColorTokens.swift is out of date. Run: python3 scripts/design/build_tokens.py")
            return 1
        print("tokens: up to date")
        return 0
    OUTPUT.write_text(swift)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
